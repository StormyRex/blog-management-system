<?php

require 'vendor/autoload.php';

/*
|--------------------------------------------------------------------------
| Session
|--------------------------------------------------------------------------
*/

if (session_status() === PHP_SESSION_NONE) {

    session_start();

}

/*
|--------------------------------------------------------------------------
| Timezone
|--------------------------------------------------------------------------
*/

date_default_timezone_set('Asia/Kolkata');

/*
|--------------------------------------------------------------------------
| Base URLs
|--------------------------------------------------------------------------
*/

if (!defined('BASE_URL')) {
    $isLocal = isset($_SERVER['HTTP_HOST']) && (
        in_array($_SERVER['HTTP_HOST'], ['localhost', '127.0.0.1'], true) ||
        str_starts_with($_SERVER['HTTP_HOST'], '192.168.')
    );

    if ($isLocal) {
        define('BASE_URL', 'http://localhost/blog-management-system');
    } else {
        $protocol = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https' : 'http';
        define('BASE_URL', $protocol . '://' . $_SERVER['HTTP_HOST']);
    }
}

if (!defined('BASE_API_URL')) {

    define(
        'BASE_API_URL',
        BASE_URL . '/api'
    );

}

/*
|--------------------------------------------------------------------------
| Frontend Routes
|--------------------------------------------------------------------------
*/

$frontendRoutes = require 'api/Config/FrontendRouteConfig.php';

/*
|--------------------------------------------------------------------------
| API Routes
|--------------------------------------------------------------------------
*/

$apiRoutes = require 'api/Config/ApiRouteConfig.php';

/*
|--------------------------------------------------------------------------
| Merge Routes
|--------------------------------------------------------------------------
*/

$routes = array_merge(
    $frontendRoutes,
    $apiRoutes
);

/*
|--------------------------------------------------------------------------
| Current URL
|--------------------------------------------------------------------------
*/

$url = $_GET['url'] ?? '/';

$url = '/' . trim($url, '/');

if ($url === '//') {

    $url = '/';

}

/*
|--------------------------------------------------------------------------
| Route Match
|--------------------------------------------------------------------------
*/

$routeTarget = $routes[$url] ?? null;

/*
|--------------------------------------------------------------------------
| Route Found
|--------------------------------------------------------------------------
*/

if ($routeTarget) {

    /*
    |--------------------------------------------------------------------------
    | Direct PHP File Route
    |--------------------------------------------------------------------------
    */

    if (is_string($routeTarget)) {

        $filePath = __DIR__ . '/' . ltrim(
            $routeTarget,
            '/'
        );

        if (file_exists($filePath)) {

            require $filePath;

            exit;

        }

    }

}

/*
|--------------------------------------------------------------------------
| 404
|--------------------------------------------------------------------------
*/

http_response_code(404);

$errorPath = __DIR__ . '/pages/errors/404.php';

if (file_exists($errorPath)) {

    require $errorPath;

} else {

    echo '404 Not Found';

}